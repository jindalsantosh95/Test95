namespace VAA.Facade.PDMFacade.Domain
{
    public class RetroCreditRequest
    {
        /// <summary>
        /// Random based Universal Unique Identifier
        /// Mandatory
        /// </summary>
        public string? TrackID { get; set; }
        /// <summary>
        /// IATA carrier code of the carrier code whose FF program the customer belongs to
        /// /// Mandatory
        /// </summary>
        public string? FFPCarrierCode { get; set; }
        /// <summary>
        /// Info from the FFP system
        /// /// Mandatory
        /// </summary>
        public string? FFPAccountNumber { get; set; }
        /// <summary>
        /// Passenger last name
        /// /// Mandatory
        /// </summary>
        public string? PassengerLastName { get; set; }
        /// <summary>
        /// Passenger first name
        /// /// Mandatory
        /// </summary>
        public string? PassengerFirstName { get; set; }
        /// <summary>
        /// Member’s Date of Birth
        /// Optional
        /// </summary>
        public string? FFPMemberDateOfBirth { get; set; }
        /// <summary>
        /// IATA carrier code of the operating carrier
        /// Mandatory
        /// </summary>
        public string? OperatingCarrierCode { get; set; }
        /// <summary>
        /// Flight Number
        /// Mandatory
        /// </summary>
        public string? OperatingFlightNumber { get; set; }
        /// <summary>
        /// Date to be in following format YYYYMMDD
        /// Mandatory
        /// </summary>
        public string? ScheduledFlightSegmentDepartureDate { get; set; }
        /// <summary>
        /// Origin IATA Airport code
        /// Mandatory
        /// </summary>
        public string? FlightSegmentOrigin { get; set; }
        /// <summary>
        /// Destination IATA Airport code
        /// Mandatory
        /// </summary>
        public string? FlightSegmentDestination { get; set; }
        /// <summary>
        /// E-Ticket 
        /// Mandatory
        /// </summary>
        public string? EticketNumber { get; set; }
        /// <summary>
        /// Seat number allocated
        /// Optional
        /// </summary>
        public string? SeatNumber { get; set; }
        /// <summary>
        /// Sequence number as printed on boarding pass or e-ticket
        /// Optional
        /// </summary>
        public int SequenceNumber { get; set; }
        /// <summary>
        /// As printed on boarding pass or e-ticket
        /// Optional
        /// </summary>
        public string? OperatingCarrierRecordLocator { get; set; }
        /// <summary>
        /// A percentage generated by SkyTeam based on how close the retro credit activity is initiated in comparison with the entire retro window
        /// Manadatory
        /// 90 – End of retro window
        /// 50 – Middle of retro window
        /// 30 – Begin of retro window
        /// </summary>
        public int RetroRequestClosenessPercentage { get; set; }
    }
}
