using VAA.EAPI.GraphQL.Common.Entities;
using VAA.EAPI.GraphQL.Common.Helper;
using VAA.EAPI.GraphQL.Common.Serialisation;
using VAA.EAPI.GraphQL.Domain.WebForms.Infrastructure.RefundMicroservice.Interfaces;
using VAA.EAPI.GraphQL.Domain.WebForms.Infrastructure.RefundMicroservice.Models;
using VAA.EAPI.GraphQL.Domain.WebForms.Models.Refunds;
using VAA.EAPI.GraphQL.Infrastructure.Interfaces;

namespace VAA.EAPI.GraphQL.Domain.WebForms.Infrastructure.RefundMicroservice.Services
{
    public class RefundProvider : IRefundProvider
    {
        private readonly IHttpConnector _connector;

        public RefundProvider(IHttpConnector connector)
        {
            _connector = connector ?? throw new ArgumentNullException(nameof(connector));
        }

        public async Task<RefundForm> CheckForDuplicates(RefundForm requestForm)
        {
            string uri = $"{ConfigReader.Get(Common.Constants.Environment.CRMRefundStatusUrl)}";
            APIResponse<RefundRequestForm> apiResponse = await _connector.SendAsync<RefundRequestForm>(uri, GetHeaders(), null, HttpMethod.Post, Json.Serialize((RefundRequestForm)requestForm));

            // Map the microservice response back to the request form entries to indicate which entries are duplicates based on the presence of a claim number which is generated by CRM when a refund request is submitted. This will be used in the UI to display a warning message to the user that a refund request has already been submitted for that passenger / flight combination.
            requestForm.Entries = apiResponse.Response.Entries.Select(entry => (RefundItem)entry).ToList();

            return requestForm;
        }

        public async Task<string> SubmitRefundRequest(RefundForm form)
        {
            string uri = $"{ConfigReader.Get(Common.Constants.Environment.CRMRefundSubmitUrl)}";
            var body = Json.Serialize((RefundRequestForm)form);
            APIResponse<RefundSubmissionResponse> apiResponse = await _connector.SendAsync<RefundSubmissionResponse>(uri, GetHeaders(), null, HttpMethod.Post, body);

            return apiResponse.Response.ClaimNumber;
        }

        private Dictionary<string, string> GetHeaders()
        {
            return new Dictionary<string, string>
                {
                    { "Ocp-Apim-Subscription-Key", ConfigReader.Get(Common.Constants.Environment.CRMRefundOcpKey) }
                };
        }
    }
}
