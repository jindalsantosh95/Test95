$ErrorActionPreference = 'Stop'
$temporary = Join-Path ([IO.Path]::GetTempPath()) ([guid]::NewGuid().ToString('N'))
$project = 'VAA.EAPI.Automation/VAA.EAPI.Automation.MobileApp.UI'
$manifest = Get-Content -Raw (Join-Path $PSScriptRoot '../config/automation-suites/mobile-search-book-sanity.json') | ConvertFrom-Json
$names = @('GITHUB_ACTIONS', 'MOBILE_APP_ID') + @($manifest.requiredSecrets)
$original = @{}
foreach ($name in $names) { $original[$name] = [Environment]::GetEnvironmentVariable($name) }
try {
    foreach ($directory in @('scripts', 'config/automation-suites', $project, "$project/Contracts")) {
        New-Item -ItemType Directory -Path (Join-Path $temporary $directory) -Force | Out-Null
    }
    Copy-Item (Join-Path $PSScriptRoot 'configure-mobile-sanity-run.ps1') (Join-Path $temporary 'scripts')
    Copy-Item (Join-Path $PSScriptRoot '../config/automation-suites/mobile-search-book-sanity.json') (Join-Path $temporary 'config/automation-suites')
    Copy-Item (Join-Path $PSScriptRoot "../$project/local.settings.local.example.json") (Join-Path $temporary $project)
    Copy-Item (Join-Path $PSScriptRoot "../$project/Contracts/search-book-automation-contract.json") (Join-Path $temporary "$project/Contracts")
    $script = Join-Path $temporary 'scripts/configure-mobile-sanity-run.ps1'
    $output = Join-Path $temporary "$project/local.settings.local.json"
    foreach ($name in $manifest.requiredSecrets) { [Environment]::SetEnvironmentVariable($name, 'synthetic-test-value') }
    $env:GITHUB_ACTIONS = 'true'
    $env:MOBILE_APP_ID = 'bs://0000000000000000000000000000000000000000'
    & $script -BuildName 'Synthetic-Sanity'
    $settings = Get-Content -Raw $output | ConvertFrom-Json
    if ($settings.RunMode -ne 'Remote' -or $settings.BrowserStack.Build -ne 'Synthetic-Sanity' -or
        $settings.BrowserStack.Project -ne 'Virgin Atlantic Mobile - Search and Book' -or
        $settings.BrowserStack.Profile -ne 'Diagnostic' -or
        $settings.BrowserStack.NetworkLogs -ne $true -or
        $settings.Loyalty.Password -ne 'synthetic-test-value' -or $settings.BackendValidation.Enabled -or
        $settings.BrowserStack.CaptureNetworkContent -ne $false) { throw 'Incorrect remote configuration' }
    Write-Host 'PASS: remote settings generated using synthetic secrets'
    foreach ($pack in @('Regression', 'Targeted', 'Sanity')) {
        & $script -BuildName "Synthetic-$pack" -Pack $pack
        $settings = Get-Content -Raw $output | ConvertFrom-Json
        if ($settings.BackendValidation.Enabled -ne ($pack -eq 'Regression') -or
            $settings.BackendValidation.Environment -ne 'SIT' -or
            $settings.BrowserStack.CaptureNetworkContent -ne $false) { throw 'Incorrect backend opt-in or diagnostics' }
        Write-Host "PASS: $pack backend opt-in"
    }
    $contract = Get-Content -Raw (Join-Path $temporary "$project/Contracts/search-book-automation-contract.json") | ConvertFrom-Json
    foreach ($id in @('TC41', 'TC42', 'TC48')) {
        $method = ($contract.scenarios | Where-Object id -eq $id).testMethod
        & $script -BuildName 'Synthetic-Targeted' -Pack Targeted -TestName $method
        $settings = Get-Content -Raw $output | ConvertFrom-Json
        if ($settings.BackendValidation.Enabled -ne ($id -in @('TC41', 'TC42'))) { throw "Incorrect targeted backend opt-in for $id" }
        Write-Host "PASS: $id targeted backend opt-in"
    }
    foreach ($case in @('missing-secret', 'invalid-app', 'local-guard')) {
        $env:BROWSERSTACK_ACCESS_KEY = if ($case -eq 'missing-secret') { '' } else { 'synthetic-test-value' }
        $env:MOBILE_APP_ID = if ($case -eq 'invalid-app') { 'bad' } else { 'bs://0000000000000000000000000000000000000000' }
        $env:GITHUB_ACTIONS = if ($case -eq 'local-guard') { 'false' } else { 'true' }
        $before = Get-FileHash $output
        $rejected = $false
        try { & $script -BuildName 'MustNotWrite' } catch { $rejected = $true }
        if (-not $rejected -or (Get-FileHash $output).Hash -ne $before.Hash) { throw "Guard failed: $case" }
        Write-Host "PASS: $case rejected without changing settings"
    }
} finally {
    foreach ($name in $names) { [Environment]::SetEnvironmentVariable($name, $original[$name]) }
    # This directory was generated by this fixture and contains synthetic credentials only.
    Remove-Item -LiteralPath $temporary -Recurse -Force
}
